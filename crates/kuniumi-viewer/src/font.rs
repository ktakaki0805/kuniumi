/// U+00B0 of `font8x8_ext_latin.h`.
const DEGREE: [u8; 8] = [0x1C, 0x36, 0x36, 0x1C, 0x00, 0x00, 0x00, 0x00]; // U+00B0 (degree)

/// The glyph of `c` in the atlas: U+0020 to U+007E in order from 0, `°`
/// after them, and for any other character the glyph of `?`.
pub fn glyph(c: char) -> u32 {
    match c {
        ' '..='~' => u32::from(c) - 0x20,
        '°' => DEGREE_GLYPH,
        _ => u32::from('?') - 0x20,
    }
}

/// The rows of `glyph`, from the top, the least significant bit leftmost.
///
/// # Panics
///
/// If `glyph` is not below [`GLYPH_COUNT`].
pub fn rows(glyph: u32) -> [u8; 8] {
    match glyph {
        DEGREE_GLYPH => DEGREE,
        SOLID => [0xFF; 8],
        _ => BASIC[glyph as usize],
    }
}

/// The atlas texel at the top-left corner of `glyph`: glyphs fill the rows
/// of [`ATLAS_COLUMNS`] in order.
pub fn glyph_origin(glyph: u32) -> [u32; 2] {
    [
        GLYPH_PX * (glyph % ATLAS_COLUMNS),
        GLYPH_PX * (glyph / ATLAS_COLUMNS),
    ]
}

/// The atlas, [`ATLAS_SIZE`] texels row-major from the top, one byte per
/// texel: 255 where a glyph's pixel is set, 0 elsewhere.
pub fn atlas() -> Vec<u8> {
    let [width, height] = ATLAS_SIZE;
    let mut texels = vec![0; (width * height) as usize];
    for g in 0..GLYPH_COUNT {
        let [x0, y0] = glyph_origin(g);
        for (row, bits) in (0..).zip(rows(g)) {
            for col in 0..GLYPH_PX {
                if (bits >> col) & 1 == 1 {
                    texels[((y0 + row) * width + x0 + col) as usize] = 255;
                }
            }
        }
    }
    texels
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `glyph` as drawn in `atlas`, one string per row: `X` for a set
    /// texel, `.` for a clear one.
    fn drawn(atlas: &[u8], glyph: u32) -> Vec<String> {
        let [x0, y0] = glyph_origin(glyph);
        let width = ATLAS_SIZE[0];
        (y0..y0 + GLYPH_PX)
            .map(|y| {
                (x0..x0 + GLYPH_PX)
                    .map(|x| match atlas[(y * width + x) as usize] {
                        0 => '.',
                        255 => 'X',
                        other => panic!("texel {other}"),
                    })
                    .collect()
            })
            .collect()
    }

    #[test]
    fn the_letter_a_as_the_readme_documents() {
        // The README's "Encoding": `A` (0x41) is encoded as
        // { 0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00} and drawn so.
        assert_eq!(
            rows(glyph('A')),
            [0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]
        );
        assert_eq!(
            drawn(&atlas(), glyph('A')),
            [
                "..XX....", ".XXXX...", "XX..XX..", "XX..XX..", "XXXXXX..", "XX..XX..", "XX..XX..",
                "........",
            ]
        );
    }

    #[test]
    fn glyphs_by_hand() {
        // Read off font8x8_basic.h and font8x8_ext_latin.h.
        let cases: [(char, u32, [u8; 8]); 7] = [
            (' ', 0, [0x00; 8]),
            ('!', 1, [0x18, 0x3C, 0x3C, 0x18, 0x18, 0x00, 0x18, 0x00]),
            ('0', 16, [0x3E, 0x63, 0x73, 0x7B, 0x6F, 0x67, 0x3E, 0x00]),
            ('?', 31, [0x1E, 0x33, 0x30, 0x18, 0x0C, 0x00, 0x0C, 0x00]),
            ('g', 71, [0x00, 0x00, 0x6E, 0x33, 0x33, 0x3E, 0x30, 0x1F]),
            ('~', 94, [0x6E, 0x3B, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]),
            ('°', 95, [0x1C, 0x36, 0x36, 0x1C, 0x00, 0x00, 0x00, 0x00]),
        ];
        for (c, index, expected) in cases {
            assert_eq!(glyph(c), index, "{c:?}");
            assert_eq!(rows(index), expected, "{c:?}");
        }
        let atlas = atlas();
        // The descender of `g` reaches the last row; the degree sign sits on
        // top.
        assert_eq!(
            drawn(&atlas, glyph('g')),
            [
                "........", "........", ".XXX.XX.", "XX..XX..", "XX..XX..", ".XXXXX..", "....XX..",
                "XXXXX...",
            ]
        );
        assert_eq!(
            drawn(&atlas, glyph('°')),
            [
                "..XXX...", ".XX.XX..", ".XX.XX..", "..XXX...", "........", "........", "........",
                "........",
            ]
        );
        assert_eq!(rows(SOLID), [0xFF; 8]);
        assert_eq!(drawn(&atlas, SOLID), ["XXXXXXXX"; 8]);
        // Outside the font: `?`.
        for c in ['\u{7F}', '\n', '\t', '\u{1F}', 'é', '±', '日', '\u{1F600}'] {
            assert_eq!(glyph(c), glyph('?'), "{c:?}");
        }
    }

    /// FNV-1a, 64 bits (Fowler, Noll and Vo).
    fn fnv1a64(bytes: impl IntoIterator<Item = u8>) -> u64 {
        bytes.into_iter().fold(0xCBF2_9CE4_8422_2325, |h, b| {
            (h ^ u64::from(b)).wrapping_mul(0x0000_0100_0000_01B3)
        })
    }

    #[test]
    fn the_table_matches_its_source() {
        // Printed by tools/font8x8_table.py, which parses the headers at the
        // pinned commit (SHA-256 checked): the 760 bytes of U+0020 to U+007E
        // and the 8 of U+00B0.
        let bytes = BASIC.iter().flatten().chain(&DEGREE).copied();
        assert_eq!(fnv1a64(bytes), 0x519f_5f86_e7e6_09f5);
        // The hash itself, on the test vectors of its authors: "" and "a".
        assert_eq!(fnv1a64([]), 0xcbf2_9ce4_8422_2325);
        assert_eq!(fnv1a64(*b"a"), 0xaf63_dc4c_8601_ec8c);
    }

    #[test]
    fn the_atlas_holds_every_glyph() {
        assert_eq!(ATLAS_SIZE, [128, 56]);
        let atlas = atlas();
        assert_eq!(atlas.len(), 128 * 56);
        assert_eq!(glyph_origin(0), [0, 0]);
        assert_eq!(glyph_origin(17), [8, 8]);
        assert_eq!(glyph_origin(SOLID), [0, 48]);
        let mut covered = vec![false; atlas.len()];
        for g in 0..GLYPH_COUNT {
            let [x0, y0] = glyph_origin(g);
            for (row, bits) in rows(g).into_iter().enumerate() {
                for col in 0..8 {
                    let k = ((y0 + row as u32) * 128 + x0 + col) as usize;
                    let set = (bits >> col) & 1 == 1;
                    assert_eq!(atlas[k], if set { 255 } else { 0 }, "glyph {g}");
                    covered[k] = true;
                }
            }
        }
        // The rest of the last row is clear.
        assert!(atlas.iter().zip(&covered).all(|(&t, &c)| c || t == 0));
        assert_eq!(covered.iter().filter(|&&c| c).count(), 97 * 64);
    }
}
