//! The bitmap font of the panel (ticket MV-06): 8 × 8 glyphs for U+0020 to
//! U+007E and the degree sign, and the atlas texture that holds them.
//!
//! Ported from font8x8 by Daniel Hepper, <https://github.com/dhepper/font8x8>
//! at commit `8e279d2d864e79128e96188a6b9526cfa3fbfef9`: [`BASIC`] is
//! U+0020 to U+007E of `font8x8_basic.h` and [`DEGREE`] is U+00B0 of
//! `font8x8_ext_latin.h`. The headers derive from Marcel Sondaar's
//! `font8_8.asm` after the IBM VGA fonts; the README and both headers give
//! the licence as "Public Domain". See `THIRD_PARTY.md`;
//! `tools/font8x8_table.py` prints the tables from the source again.
//!
//! Each glyph is 8 bytes, one per row from the top; bit `k` of a row (the
//! least significant bit first) is the pixel in column `k` from the left
//! (the README's "Encoding").

/// The side of a glyph (font pixels).
pub const GLYPH_PX: u32 = 8;

/// The glyph of the degree sign, after the 95 of [`BASIC`].
