//! Tests for `predicates` (ticket M1-03).
//!
//! Expected signs never come from `robust`: they come from two exact
//! evaluations written here, from the definition
//! `det[b − a; c − a; d − a]`:
//!
//! - [`det_i128`] for integer coordinates (|c| ≤ 2²⁰, so every term fits);
//! - [`exact_orientation`] for any doubles in the precondition's range: every
//!   coordinate is `m · 2^e` exactly (`m` an integer, |m| < 2⁵³), all twelve
//!   are scaled by the same power of two to integers, and the determinant is
//!   evaluated in 512-bit two's-complement integers ([`Wide`]). Scaling by a
//!   positive factor does not change the sign. It is checked against
//!   [`det_i128`] in `wide_reference_matches_i128`.
//!
//! Tests:
//! - `sign_convention_*` (criterion 4): the unit axes, all 24 orders of
//!   (0, x̂, ŷ, ẑ) against the parity of the permutation.
//! - `matches_i128_*` (criterion 1): 10⁵ quadruples each of uniform integers in
//!   [−2²⁰, 2²⁰]³, near-coplanar integers up to 2²⁰ with exact determinant
//!   −1, 0 or 1, and small integers in [−3, 3]³.
//! - `exactly_coplanar_points_give_zero` (criterion 2).
//! - `one_ulp_perturbations_match_exact_evaluation` (criterion 3).
//! - `scaling_to_the_ends_of_the_range_keeps_the_sign` and
//!   `opposite_ends_of_the_range_in_one_quadruple_keep_the_sign`: the
//!   precondition's range [2⁻²⁰⁰, 2²⁰⁰] at both ends, and both ends at once.
//! - `precondition_*`: the debug assertion accepts zero and the ends of the
//!   range, and rejects one ULP outside them and NaN.
//!
//! Run with `--nocapture` to see how many signs a naive `f64` determinant
//! gets wrong on the same inputs.

use kuniumi_math::{Rng, Vec3, det};

use super::{Orientation, orient3d};
use crate::coords::from_lat_lon;

/// Seed of every random stream in these tests.
const SEED: u64 = 20_261_108;

/// Random quadruples per integer family (criterion 1).
const INTEGER_QUADRUPLES: usize = 100_000;

/// The largest integer coordinate of criterion 1.
const INTEGER_BOUND: i64 = 1 << 20;

/// `Positive`, `Zero` or `Negative` for the sign of `s`.
fn orientation_of_sign(s: i32) -> Orientation {
    match s.signum() {
        1 => Orientation::Positive,
        -1 => Orientation::Negative,
        _ => Orientation::Zero,
    }
}

/// The sign of a double as an orientation (NaN gives `Zero`).
fn orientation_of_f64(x: f64) -> Orientation {
    if x > 0.0 {
        Orientation::Positive
    } else if x < 0.0 {
        Orientation::Negative
    } else {
        Orientation::Zero
    }
}

/// `orient3d` on a quadruple.
fn orient(q: [Vec3; 4]) -> Orientation {
    orient3d(q[0], q[1], q[2], q[3])
}

/// The plain `f64` determinant `((b − a) × (c − a)) · (d − a)`, rounded at
/// every step: what `orient3d` replaces.
fn naive(q: [Vec3; 4]) -> Orientation {
    let [a, b, c, d] = q;
    orientation_of_f64((b - a).cross(c - a).dot(d - a))
}

/// The 24 orders of four items, with the parity of each permutation
/// (`true` for even), generated by Heap's algorithm.
fn permutations_of_four() -> Vec<([usize; 4], bool)> {
    let mut out = Vec::with_capacity(24);
    let mut p = [0, 1, 2, 3];
    let mut even = true;
    let mut c = [0usize; 4];
    out.push((p, even));
    let mut i = 1;
    while i < 4 {
        if c[i] < i {
            if i % 2 == 0 {
                p.swap(0, i);
            } else {
                p.swap(c[i], i);
            }
            even = !even;
            out.push((p, even));
            c[i] += 1;
            i = 1;
        } else {
            c[i] = 0;
            i += 1;
        }
    }
    out
}

/// `q` in the order `order`.
fn reorder(q: [Vec3; 4], order: [usize; 4]) -> [Vec3; 4] {
    [q[order[0]], q[order[1]], q[order[2]], q[order[3]]]
}

