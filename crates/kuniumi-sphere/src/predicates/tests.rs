#[test]
fn wide_arithmetic() {
    let w = Wide::from_i64;
    assert_eq!(w(-3).mul(w(5)), w(-15));
    assert_eq!(w(-3).mul(w(-5)), w(15));
    assert_eq!(w(7).sub(w(9)), w(-2));
    assert_eq!(w(i64::MIN).mul(w(i64::MIN)), w(1).shl(126));
    assert_eq!(w(-1).shl(200).neg(), w(1).shl(200));
    // (2¹⁰⁰ + 1)(2¹⁰⁰ − 1) = 2²⁰⁰ − 1.
    let big = w(1).shl(100);
    assert_eq!(big.add(w(1)).mul(big.sub(w(1))), w(1).shl(200).sub(w(1)));
    assert_eq!(w(1).shl(510).signum(), 1);
    assert_eq!(w(-1).shl(510).signum(), -1);
    assert_eq!(w(5).sub(w(5)).signum(), 0);
    // A product crossing many limbs: (2¹⁵⁰ + 3)³ = 2⁴⁵⁰ + 9·2³⁰⁰ + 27·2¹⁵⁰ + 27.
    let x = w(1).shl(150).add(w(3));
    let expected = w(1)
        .shl(450)
        .add(w(9).shl(300))
        .add(w(27).shl(150))
        .add(w(27));
    assert_eq!(x.mul(x).mul(x), expected);
    assert_eq!(x.mul(x).mul(x.neg()), expected.neg());
}

#[test]
fn decompose_is_exact() {
    assert_eq!(decompose(0.0), (0, 0));
    assert_eq!(decompose(-0.0), (0, 0));
    assert_eq!(decompose(1.0), (1 << 52, -52));
    assert_eq!(decompose(-0.75), (-(3 << 51), -53));
    assert_eq!(decompose(f64::MIN_POSITIVE), (1 << 52, -1074));
    assert_eq!(decompose(f64::from_bits(1)), (1, -1074));
}

