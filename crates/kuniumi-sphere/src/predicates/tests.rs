// Exact reference 1: i128 for integer coordinates.

/// `det[b − a; c − a; d − a] = (b − a) · ((c − a) × (d − a))` of integer
/// points, exactly. With |c| ≤ 2²⁰ the differences are below 2²¹ and every
/// term below 2⁶⁴, far inside `i128`.
fn det_i128(q: [[i64; 3]; 4]) -> i128 {
    let diff = |p: [i64; 3], o: [i64; 3]| {
        [
            i128::from(p[0]) - i128::from(o[0]),
            i128::from(p[1]) - i128::from(o[1]),
            i128::from(p[2]) - i128::from(o[2]),
        ]
    };
    let [a, b, c, d] = q;
    let (u, w, t) = (diff(b, a), diff(c, a), diff(d, a));
    u[0] * (w[1] * t[2] - w[2] * t[1])
        + u[1] * (w[2] * t[0] - w[0] * t[2])
        + u[2] * (w[0] * t[1] - w[1] * t[0])
}

/// An integer quadruple as points (exact: every integer is below 2⁵³).
fn to_points(q: [[i64; 3]; 4]) -> [Vec3; 4] {
    q.map(|p| Vec3::new(p[0] as f64, p[1] as f64, p[2] as f64))
}

// ---------------------------------------------------------------------------
// Exact reference 2: 512-bit integers for any doubles.

/// A 512-bit two's-complement integer, eight little-endian 64-bit limbs.
/// Addition, subtraction, multiplication and left shifts wrap modulo 2⁵¹²,
/// so every result is exact while it stays inside (−2⁵¹¹, 2⁵¹¹).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Wide([u64; 8]);

impl Wide {
    const ZERO: Self = Self([0; 8]);

    fn from_i64(x: i64) -> Self {
        let fill = if x < 0 { u64::MAX } else { 0 };
        let mut limbs = [fill; 8];
        limbs[0] = x as u64;
        Self(limbs)
    }

    /// `self · 2^k` for `k < 512`.
    fn shl(self, k: u32) -> Self {
        assert!(k < 512);
        let (limbs, bits) = ((k / 64) as usize, k % 64);
        let mut r = [0u64; 8];
        for (i, limb) in r.iter_mut().enumerate().skip(limbs) {
            let src = i - limbs;
            *limb = self.0[src] << bits;
            if bits > 0 && src > 0 {
                *limb |= self.0[src - 1] >> (64 - bits);
            }
        }
        Self(r)
    }

    fn add(self, o: Self) -> Self {
        let mut r = [0u64; 8];
        let mut carry = false;
        for (i, limb) in r.iter_mut().enumerate() {
            let (s1, c1) = self.0[i].overflowing_add(o.0[i]);
            let (s2, c2) = s1.overflowing_add(u64::from(carry));
            *limb = s2;
            carry = c1 || c2;
        }
        Self(r)
    }

    fn neg(self) -> Self {
        Self(self.0.map(|l| !l)).add(Self::from_i64(1))
    }

    fn sub(self, o: Self) -> Self {
        self.add(o.neg())
    }

    /// Schoolbook multiplication, keeping the low 512 bits.
    fn mul(self, o: Self) -> Self {
        let mut r = [0u64; 8];
        for i in 0..8 {
            let mut carry: u128 = 0;
            for j in 0..(8 - i) {
                // At most (2⁶⁴ − 1)² + 2 (2⁶⁴ − 1) = 2¹²⁸ − 1.
                let t = u128::from(self.0[i]) * u128::from(o.0[j]) + u128::from(r[i + j]) + carry;
                r[i + j] = t as u64;
                carry = t >> 64;
            }
        }
        Self(r)
    }

    fn signum(self) -> i32 {
        if self.0[7] >> 63 == 1 {
            -1
        } else if self.0 == [0; 8] {
            0
        } else {
            1
        }
    }
}

/// `x = m · 2^e` exactly, with `m` an integer, |m| < 2⁵³. Zero gives (0, 0).
fn decompose(x: f64) -> (i64, i32) {
    assert!(x.is_finite());
    if x == 0.0 {
        return (0, 0);
    }
    let bits = x.to_bits();
    let biased = ((bits >> 52) & 0x7ff) as i32;
    let fraction = (bits & ((1 << 52) - 1)) as i64;
    let (m, e) = if biased == 0 {
        (fraction, -1074)
    } else {
        (fraction | (1 << 52), biased - 1075)
    };
    if bits >> 63 == 1 { (-m, e) } else { (m, e) }
}

/// The exact sign of `det[b − a; c − a; d − a]` for doubles.
///
/// All twelve coordinates are scaled by `2^(−e_min)`, with `e_min` the
/// smallest exponent of a non-zero coordinate, which makes them integers
/// below 2^(53 + spread). The spread of exponents is asserted to be at most
/// 100, so the terms stay below 2^(3 · 154 + 2) < 2⁵¹¹.
fn exact_orientation(q: [Vec3; 4]) -> Orientation {
    let coords = q.map(|p| [p.x, p.y, p.z]);
    let parts = coords.map(|p| p.map(decompose));
    let Some(e_min) = parts
        .iter()
        .flatten()
        .filter(|(m, _)| *m != 0)
        .map(|(_, e)| *e)
        .min()
    else {
        return Orientation::Zero;
    };
    let scaled = parts.map(|p| {
        p.map(|(m, e)| {
            if m == 0 {
                Wide::ZERO
            } else {
                let k = e - e_min;
                assert!(k <= 100, "exponent spread {k} too large for the reference");
                Wide::from_i64(m).shl(k as u32)
            }
        })
    });
    let [a, b, c, d] = scaled;
    let diff = |p: [Wide; 3], o: [Wide; 3]| [p[0].sub(o[0]), p[1].sub(o[1]), p[2].sub(o[2])];
    let (u, w, t) = (diff(b, a), diff(c, a), diff(d, a));
    let det = u[0]
        .mul(w[1].mul(t[2]).sub(w[2].mul(t[1])))
        .add(u[1].mul(w[2].mul(t[0]).sub(w[0].mul(t[2]))))
        .add(u[2].mul(w[0].mul(t[1]).sub(w[1].mul(t[0]))));
    orientation_of_sign(det.signum())
}

