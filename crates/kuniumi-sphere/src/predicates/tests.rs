// Criterion 4: the sign convention.

#[test]
fn sign_convention_on_unit_axes() {
    use Orientation::{Negative, Positive, Zero};
    let (o, x, y, z) = (Vec3::ZERO, Vec3::X, Vec3::Y, Vec3::Z);
    // (0, x̂, ŷ, ẑ) is right-handed: det[x̂; ŷ; ẑ] = 1.
    assert_eq!(orient3d(o, x, y, z), Positive);
    // x̂, ŷ, ẑ appear counter-clockwise from outside the octahedron (their
    // normal (ŷ − x̂) × (ẑ − x̂) = (1, 1, 1) points away from the origin), so
    // the origin is below that face and (1, 1, 1) above it.
    assert_eq!(orient3d(x, y, z, o), Negative);
    assert_eq!(orient3d(x, y, z, Vec3::new(1.0, 1.0, 1.0)), Positive);
    assert_eq!(orient3d(x, y, z, Vec3::new(0.25, 0.25, 0.5)), Zero);
    // Seen from below, the same face is clockwise.
    assert_eq!(orient3d(x, z, y, o), Positive);
}

#[test]
fn sign_convention_follows_permutation_parity() {
    let q = [Vec3::ZERO, Vec3::X, Vec3::Y, Vec3::Z];
    let perms = permutations_of_four();
    assert_eq!(perms.len(), 24);
    let mut seen: Vec<[usize; 4]> = perms.iter().map(|(p, _)| *p).collect();
    seen.sort_unstable();
    seen.dedup();
    assert_eq!(seen.len(), 24);
    for (order, even) in perms {
        let expected = if even {
            Orientation::Positive
        } else {
            Orientation::Negative
        };
        let r = reorder(q, order);
        assert_eq!(orient(r), expected, "order {order:?}");
        // The definition evaluated directly (exact on these small integers).
        assert_eq!(naive(r), expected, "order {order:?}");
    }
}

