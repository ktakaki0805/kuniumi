/// `2^k` for −1022 ≤ k ≤ 1023.
fn pow2(k: i32) -> f64 {
    assert!((-1022..=1023).contains(&k));
    f64::from_bits(((1023 + k) as u64) << 52)
}

/// The unbiased exponent of a normal double: `x ∈ [2^e, 2^(e+1))`.
fn exponent(x: f64) -> i32 {
    ((x.abs().to_bits() >> 52) & 0x7ff) as i32 - 1023
}

#[test]
fn scaling_to_the_ends_of_the_range_keeps_the_sign() {
    let low = pow2(-200);
    let high = pow2(200);
    let mut checked = 0;
    for (name, q) in perturbed_quadruples() {
        let coords: Vec<f64> = q
            .iter()
            .flat_map(|p| [p.x, p.y, p.z])
            .filter(|x| *x != 0.0)
            .collect();
        let e_lo = coords.iter().map(|x| exponent(*x)).min().unwrap();
        let e_hi = coords.iter().map(|x| exponent(*x)).max().unwrap();
        let expected = exact_orientation(q);
        // Smallest coordinate moved into [2⁻²⁰⁰, 2⁻¹⁹⁹), largest into
        // [2¹⁹⁹, 2²⁰⁰). Multiplying by a power of two is exact here and
        // multiplies the determinant by a positive factor.
        for scale in [pow2(-200 - e_lo), pow2(199 - e_hi)] {
            let s = q.map(|p| p * scale);
            for p in s {
                for x in [p.x, p.y, p.z] {
                    assert!(x == 0.0 || (low..=high).contains(&x.abs()), "{name}: {x:e}");
                }
            }
            assert_eq!(exact_orientation(s), expected, "{name}: {s:?}");
            assert_eq!(orient(s), expected, "{name}: {s:?}");
            checked += 1;
        }
    }
    println!("scaled to the ends of the range: {checked} quadruples");
}

#[test]
fn opposite_ends_of_the_range_in_one_quadruple_keep_the_sign() {
    // One axis is scaled down so that its smallest non-zero coordinate lies
    // in [2⁻²⁰⁰, 2⁻¹⁹⁹), another up so that its largest lies in
    // [2¹⁹⁹, 2²⁰⁰): exponents spread by about 400 within one quadruple.
    // Scaling one axis by 2^k multiplies the determinant by 2^k > 0, so the
    // exact sign is that of the unscaled quadruple.
    let low = pow2(-200);
    let high = pow2(200);
    let mut checked = 0;
    for (name, q) in perturbed_quadruples() {
        let expected = exact_orientation(q);
        let c = q.map(|p| [p.x, p.y, p.z]);
        let exponents = |axis: usize| {
            let e: Vec<i32> = c
                .iter()
                .map(|p| p[axis])
                .filter(|x| *x != 0.0)
                .map(exponent)
                .collect();
            (e.iter().min().copied(), e.iter().max().copied())
        };
        for down in 0..3 {
            for up in 0..3 {
                if down == up {
                    continue;
                }
                let (Some(e_lo), _) = exponents(down) else {
                    continue;
                };
                let (_, Some(e_hi)) = exponents(up) else {
                    continue;
                };
                let mut scale = [1.0; 3];
                scale[down] = pow2(-200 - e_lo);
                scale[up] = pow2(199 - e_hi);
                let s = c.map(|p| Vec3::new(p[0] * scale[0], p[1] * scale[1], p[2] * scale[2]));
                for p in s {
                    for x in [p.x, p.y, p.z] {
                        assert!(x == 0.0 || (low..=high).contains(&x.abs()), "{name}: {x:e}");
                    }
                }
                assert_eq!(orient(s), expected, "{name}: {s:?}");
                checked += 1;
            }
        }
    }
    println!("opposite ends of the range in one quadruple: {checked} quadruples");
    assert!(checked > 100_000);
}

