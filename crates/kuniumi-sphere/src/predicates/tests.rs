/// A uniform integer in [−bound, bound].
fn int_in(rng: &mut Rng, bound: i64) -> i64 {
    rng.below((2 * bound + 1) as u64) as i64 - bound
}

/// Four uniform integer points in [−bound, bound]³.
fn uniform_quadruple(rng: &mut Rng, bound: i64) -> [[i64; 3]; 4] {
    core::array::from_fn(|_| core::array::from_fn(|_| int_in(rng, bound)))
}

/// `(x, y)` with `p x + q y = gcd(p, q)` (extended Euclid), and the gcd.
fn bezout(p: i64, q: i64) -> (i64, i64, i64) {
    let (mut r0, mut r1) = (p, q);
    let (mut x0, mut x1) = (1, 0);
    let (mut y0, mut y1) = (0, 1);
    while r1 != 0 {
        let k = r0.div_euclid(r1);
        (r0, r1) = (r1, r0 - k * r1);
        (x0, x1) = (x1, x0 - k * x1);
        (y0, y1) = (y1, y0 - k * y1);
    }
    (x0, y0, r0)
}

/// Four integer points in [−2²⁰, 2²⁰]³ whose exact determinant is −1, 0 or
/// 1, although their differences are up to about 2¹⁹ and the terms of the
/// determinant up to about 2⁵⁶: a hard case for floating point.
///
/// `p` and `q` are random coprime integers of magnitude 2¹⁷ to 2¹⁸, and `r`,
/// `s` complete them to a unimodular matrix, `p s − q r = 1` (extended
/// Euclid gives |r| ≤ |p| and |s| ≤ |q|). With `u = b − a = (p, q, r₁)` and
/// `v = c − a = (r, s, r₂)`, the z component of `u × v` is 1, so
/// `d = a + σ u + τ v + δ ẑ` gives `det[u; v; d − a] = δ`, with σ, τ and δ
/// in {−1, 0, 1}, r₁ and r₂ in [−2¹⁸, 2¹⁸] and `a` in [−2¹⁷, 2¹⁷]³. The axes
/// are then permuted and flipped and the points shuffled at random; the
/// expected value is recomputed from the final coordinates anyway.
fn near_coplanar_quadruple(rng: &mut Rng) -> [[i64; 3]; 4] {
    let (p, q, r, s) = loop {
        let draw = |rng: &mut Rng| {
            let m = (1 << 17) + rng.below(1 << 17) as i64;
            if rng.below(2) == 0 { m } else { -m }
        };
        let (p, q) = (draw(rng), draw(rng));
        let (x, y, g) = bezout(p, q);
        // p x + q y = ±1: then p s − q r = 1 with s = ±x, r = ∓y.
        if g.abs() == 1 {
            break (p, q, -y * g, x * g);
        }
    };
    assert_eq!(p * s - q * r, 1);
    let a: [i64; 3] = core::array::from_fn(|_| int_in(rng, 1 << 17));
    let u = [p, q, int_in(rng, 1 << 18)];
    let v = [r, s, int_in(rng, 1 << 18)];
    let (sigma, tau) = (int_in(rng, 1), int_in(rng, 1));
    let delta = int_in(rng, 1);
    let b = core::array::from_fn(|k| a[k] + u[k]);
    let c = core::array::from_fn(|k| a[k] + v[k]);
    let mut d: [i64; 3] = core::array::from_fn(|k| a[k] + sigma * u[k] + tau * v[k]);
    d[2] += delta;
    let mut q = [a, b, c, d];
    // Permute and flip the axes.
    let axes = [
        [0, 1, 2],
        [0, 2, 1],
        [1, 0, 2],
        [1, 2, 0],
        [2, 0, 1],
        [2, 1, 0],
    ];
    let perm = axes[rng.below(6) as usize];
    let flip: [i64; 3] = core::array::from_fn(|_| if rng.below(2) == 0 { 1 } else { -1 });
    for pt in &mut q {
        let old = *pt;
        *pt = core::array::from_fn(|k| flip[k] * old[perm[k]]);
    }
    // Shuffle the points (Fisher–Yates).
    for i in (1..4).rev() {
        let j = rng.below(i as u64 + 1) as usize;
        q.swap(i, j);
    }
    for pt in q {
        for x in pt {
            assert!(x.abs() <= INTEGER_BOUND);
        }
    }
    q
}

/// Signs seen in one family of inputs.
#[derive(Debug, Default)]
struct Tally {
    positive: usize,
    zero: usize,
    negative: usize,
    naive_wrong: usize,
}

impl Tally {
    fn count(&mut self, expected: Orientation, q: [Vec3; 4]) {
        match expected {
            Orientation::Positive => self.positive += 1,
            Orientation::Zero => self.zero += 1,
            Orientation::Negative => self.negative += 1,
        }
        if naive(q) != expected {
            self.naive_wrong += 1;
        }
    }

    fn total(&self) -> usize {
        self.positive + self.zero + self.negative
    }
}

/// Checks `orient3d` against [`det_i128`] on `n` quadruples from `generate`.
fn check_integer_family(
    name: &str,
    n: usize,
    mut generate: impl FnMut(&mut Rng) -> [[i64; 3]; 4],
) -> Tally {
    let mut rng = Rng::for_stream(SEED, name);
    let mut tally = Tally::default();
    for _ in 0..n {
        let qi = generate(&mut rng);
        let q = to_points(qi);
        let det = det_i128(qi);
        let expected = orientation_of_sign(det.signum() as i32);
        assert_eq!(
            orient(q),
            expected,
            "{name}: {qi:?}, exact determinant {det}"
        );
        tally.count(expected, q);
    }
    println!("{name}: {tally:?}");
    tally
}

/// One exactly coplanar quadruple of each kind used by criteria 2 and 3,
/// many of them random.
fn coplanar_quadruples() -> Vec<(&'static str, [Vec3; 4])> {
    let mut out = Vec::new();
    let mut rng = Rng::for_stream(SEED, "test/predicates/coplanar");

    // Dyadic points: coordinates k · 2⁻²⁴ in [−1, 1], s and t in [−1, 2] on
    // the same grid. Then s (b − a) is a multiple of 2⁻⁴⁸ below 4 in
    // magnitude, and d = a + s (b − a) + t (c − a) a multiple of 2⁻⁴⁸ below
    // 16: at most 52 significant bits, so every step is exact.
    let unit = 1.0 / (1u64 << 24) as f64;
    let dyadic = |rng: &mut Rng, lo: i64, hi: i64| {
        (lo + rng.below((hi - lo + 1) as u64) as i64) as f64 * unit
    };
    for _ in 0..2_000 {
        let point = |rng: &mut Rng| {
            Vec3::new(
                dyadic(rng, -(1 << 24), 1 << 24),
                dyadic(rng, -(1 << 24), 1 << 24),
                dyadic(rng, -(1 << 24), 1 << 24),
            )
        };
        let (a, b, c) = (point(&mut rng), point(&mut rng), point(&mut rng));
        let s = dyadic(&mut rng, -(1 << 24), 1 << 25);
        let t = dyadic(&mut rng, -(1 << 24), 1 << 25);
        let d = a + (b - a) * s + (c - a) * t;
        out.push(("dyadic plane", [a, b, c, d]));
    }

    // Random positions on the unit sphere (not exact unit vectors, which
    // does not matter here).
    let sphere_point = |rng: &mut Rng| {
        let z = rng.range_f64(-1.0, 1.0);
        let lat = det::asin(z);
        from_lat_lon(
            lat,
            rng.range_f64(-core::f64::consts::PI, core::f64::consts::PI),
        )
    };

    // Repeated points: any fourth point is coplanar.
    for _ in 0..100 {
        let (a, b, c) = (
            sphere_point(&mut rng),
            sphere_point(&mut rng),
            sphere_point(&mut rng),
        );
        out.push(("repeated point", [a, a, b, c]));
    }

    // Collinear a, b, c (dyadic, so c is exact) and any d.
    for _ in 0..100 {
        let point = |rng: &mut Rng| {
            Vec3::new(
                dyadic(rng, -(1 << 24), 1 << 24),
                dyadic(rng, -(1 << 24), 1 << 24),
                dyadic(rng, -(1 << 24), 1 << 24),
            )
        };
        let (a, b) = (point(&mut rng), point(&mut rng));
        let s = dyadic(&mut rng, -(1 << 24), 1 << 25);
        let c = a + (b - a) * s;
        out.push(("collinear", [a, b, c, sphere_point(&mut rng)]));
    }

    // The octahedron's equator (z = 0).
    out.push(("octahedron equator", [Vec3::X, Vec3::Y, -Vec3::X, -Vec3::Y]));

    // The faces of the cube inscribed in the unit sphere: each face lies on
    // a plane ±x = s, ±y = s or ±z = s with the same double s.
    let s = (1.0f64 / 3.0).sqrt();
    for axis in 0..3 {
        for sign in [1.0, -1.0] {
            let corner = |u: f64, v: f64| {
                let mut c = [0.0; 3];
                c[axis] = sign * s;
                c[(axis + 1) % 3] = u * s;
                c[(axis + 2) % 3] = v * s;
                Vec3::new(c[0], c[1], c[2])
            };
            out.push((
                "cube face",
                [
                    corner(1.0, 1.0),
                    corner(-1.0, 1.0),
                    corner(-1.0, -1.0),
                    corner(1.0, -1.0),
                ],
            ));
        }
    }

    // Four points of a latitude circle: the same latitude gives the same z.
    for _ in 0..500 {
        let lat = det::asin(rng.range_f64(-1.0, 1.0));
        let on_circle = |rng: &mut Rng| {
            from_lat_lon(
                lat,
                rng.range_f64(-core::f64::consts::PI, core::f64::consts::PI),
            )
        };
        out.push((
            "latitude circle",
            [
                on_circle(&mut rng),
                on_circle(&mut rng),
                on_circle(&mut rng),
                on_circle(&mut rng),
            ],
        ));
    }

    // Coordinate permutations of a point: all lie on x + y + z = const, and
    // on the sphere through the point, so they are co-circular there.
    for _ in 0..100 {
        let p = sphere_point(&mut rng);
        let (x, y, z) = (p.x, p.y, p.z);
        let perms = [
            Vec3::new(x, y, z),
            Vec3::new(y, z, x),
            Vec3::new(z, x, y),
            Vec3::new(x, z, y),
            Vec3::new(z, y, x),
            Vec3::new(y, x, z),
        ];
        for i in 0..6 {
            for j in i + 1..6 {
                for k in j + 1..6 {
                    for l in k + 1..6 {
                        out.push((
                            "coordinate permutations",
                            [perms[i], perms[j], perms[k], perms[l]],
                        ));
                    }
                }
            }
        }
    }

    // Three points of a great circle and the centre: the plane x = 0 (and,
    // with the axes rotated, y = 0 and z = 0).
    for _ in 0..300 {
        let on_circle = |rng: &mut Rng| {
            let (sin, cos) =
                det::sin_cos(rng.range_f64(-core::f64::consts::PI, core::f64::consts::PI));
            [0.0, cos, sin]
        };
        let pts = [
            on_circle(&mut rng),
            on_circle(&mut rng),
            on_circle(&mut rng),
            [0.0; 3],
        ];
        let shift = rng.below(3) as usize;
        let q = pts.map(|c| Vec3::new(c[shift % 3], c[(shift + 1) % 3], c[(shift + 2) % 3]));
        out.push(("great circle and centre", q));
    }

    out
}

/// The neighbouring double of the finite non-zero `x`, one ULP towards +∞
/// (`up`) or −∞.
fn ulp_step(x: f64, up: bool) -> f64 {
    assert!(x.is_finite() && x != 0.0);
    let bits = x.to_bits();
    // Bits grow with the magnitude, so a step away from zero adds one.
    if up == (x > 0.0) {
        f64::from_bits(bits + 1)
    } else {
        f64::from_bits(bits - 1)
    }
}

/// The coplanar quadruples of [`coplanar_quadruples`] with one non-zero
/// coordinate moved by one ULP up or down, every coordinate in turn.
fn perturbed_quadruples() -> Vec<(&'static str, [Vec3; 4])> {
    let mut out = Vec::new();
    for (name, q) in coplanar_quadruples() {
        for point in 0..4 {
            for axis in 0..3 {
                for up in [true, false] {
                    let mut c = q.map(|p| [p.x, p.y, p.z]);
                    if c[point][axis] == 0.0 {
                        continue;
                    }
                    c[point][axis] = ulp_step(c[point][axis], up);
                    out.push((name, c.map(|p| Vec3::new(p[0], p[1], p[2]))));
                }
            }
        }
    }
    out
}

